const { _electron: electron } = require('playwright-core')
const assert = require('node:assert/strict')
const { mkdtempSync, mkdirSync } = require('node:fs')
const { resolve, join } = require('node:path')
const { tmpdir } = require('node:os')

const packaged = process.argv[2] && resolve(process.argv[2])
const homeOnly = process.argv.includes('--home')
const screenshot = process.argv[3] && !process.argv[3].startsWith('--') && resolve(process.argv[3])
const uiData = mkdtempSync(join(tmpdir(), 'hdu-desktop-test-'))
const options = {
  executablePath: packaged || require('electron'),
  args: packaged ? [] : [__dirname, '--fixture'],
  env: { ...process.env, HDU_DESKTOP_TEST_UI: uiData },
  timeout: 20000,
}
if (packaged) options.env.PATH = join(process.env.SystemRoot, 'System32')
if (packaged && homeOnly) options.env.LOCALAPPDATA = mkdtempSync(join(tmpdir(), 'hdu-home-test-'))

const phase = (page, label) => page.waitForFunction(value => document.querySelector('#phase').textContent === value, label)
const error = (page, id) => page.locator('#' + id).textContent()

async function launch(overrides = {}) {
  const app = await electron.launch({ ...options, ...overrides })
  try {
    const page = await app.firstWindow()
    page.on('pageerror', error => console.error(error.stack))
    await page.locator('#start:enabled').waitFor()
    assert.equal(await page.title(), '杭电羽毛球助手')
    assert.equal(await page.evaluate(() => typeof require), 'undefined')
    assert.match(await page.locator('#release').textContent(), /\d{4}-\d\d-\d\d \d\d:\d\d/)
    return { app, page }
  } catch (err) {
    await app.close()
    throw err
  }
}

async function main() {
  let { app, page } = await launch()
  try {
    if (packaged && homeOnly) {
      const briefing = await page.evaluate(() => window.venue.load())
      assert(briefing.ok)
      assert.equal(briefing.data.config.release_days_before, 2)
      assert.equal(briefing.data.config.release_override, '')
      assert.equal(await error(page, 'hero-date'), briefing.data.config.target_date)
      assert.equal(await error(page, 'release'), briefing.data.today + ' ' + briefing.data.config.release_time + ':00')
      await page.locator('#target-date-value').click()
      await page.locator('#date-time-picker:popover-open').waitFor()
      await page.keyboard.press('Escape')
      await page.locator('#date-time-picker:popover-open').waitFor({ state: 'detached' })
      await page.waitForFunction(() => document.querySelector('#notice-meta').textContent.includes('上次成功同步'))
      const expected = await new Promise((resolve, reject) => {
        const request = require('node:https').request('https://sportmeta.hdu.edu.cn/book/client/show_notice',
          { method: 'POST', headers: { 'Content-Type': 'application/json' }, timeout: 7000 }, response => {
            let data = ''
            response.setEncoding('utf8')
            response.on('data', chunk => { data += chunk })
            response.on('end', () => { try { resolve(JSON.parse(data).message) } catch (e) { reject(e) } })
          })
        request.on('error', reject)
        request.on('timeout', () => request.destroy(new Error('公告来源超时')))
        request.end(JSON.stringify({ user_type: 2 }))
      })
      assert.equal(await error(page, 'bulletin-body'), expected || '暂无公告')
      await page.locator('#clear-status').click()
      assert.equal(await error(page, 'bulletin-body'), expected || '暂无公告')
      const firstCourt = page.locator('.court-card').first()
      await firstCourt.press('Space')
      await page.keyboard.press('ArrowRight')
      await page.keyboard.press('Space')
      const savedCourtOrder = await page.locator('#courts li').allTextContents()
      assert.deepEqual(savedCourtOrder.slice(0, 2), ['7', '6'])
      await page.locator('#earliest-start-value').click()
      await page.getByRole('button', { name: '14:00', exact: true }).click()
      await page.locator('#save').click()
      await phase(page, '配置已保存')
      await app.close()
      ;({ app, page } = await launch())
      assert.equal(await error(page, 'earliest-start-value'), '14:00')
      assert.deepEqual(await page.locator('#courts li').allTextContents(), savedCourtOrder)
      console.log(JSON.stringify({ version: await app.evaluate(({app}) => app.getVersion()),
        release: await error(page, 'release'), target: await error(page, 'hero-date'), noticeCharacters: expected.length }))
      return
    }
    if (!packaged) {
      await page.locator('#notice-expand:visible').click()
      assert.equal(await page.locator('#notice-expand').getAttribute('aria-expanded'), 'true')
      await page.locator('#notice-expand').click()
      const original = await error(page, 'bulletin-body')
      await page.locator('#notice-refresh:enabled').click()
      await page.waitForFunction(() => document.querySelector('#notice-meta').textContent.includes('更新失败，显示上次内容'))
      assert.equal(await error(page, 'bulletin-body'), original)
      await page.locator('#notice-refresh').click()
      await page.waitForFunction(() => document.querySelector('#bulletin-body').textContent === '暂无公告')
      await page.locator('#notice-refresh').click()
      await page.waitForFunction(text => document.querySelector('#bulletin-body').textContent === text, original)
      assert.deepEqual(await page.locator('#courts li').allTextContents(), ['6', '7', '5', '8', '1', '2', '3', '4', '9', '10', '11', '12'])
    }
    await page.locator('#preview').click()
    await page.waitForFunction(() => !document.querySelector('#preview').disabled)
    if (await error(page, 'phase') !== '演练完成') {
      throw new Error('Read-only preview: ' + await error(page, 'notice-message'))
    }
    if (screenshot) {
      mkdirSync(require('node:path').dirname(screenshot), { recursive: true })
      await page.screenshot({ path: screenshot })
    }
    if (!packaged) {
      assert.deepEqual(await page.locator('#candidates td:nth-child(2)').allTextContents(), ['6 号场', '7 号场', '5 号场'])
      const bulletin = await error(page, 'bulletin-body')
      await page.locator('#clear-status').click()
      await phase(page, '就绪')
      assert.equal(await error(page, 'log-count'), '')
      assert.equal(await page.locator('#candidates tr').count(), 0)
      assert.equal(await error(page, 'bulletin-body'), bulletin)
      await page.clock.install()
      await page.locator('#preview').click()
      await phase(page, '演练完成')
      await page.locator('#start:enabled').waitFor()
      await page.clock.fastForward(61000)
      await phase(page, '就绪')
      assert.equal(await error(page, 'bulletin-body'), bulletin)
      await page.locator('#start').click()
      await phase(page, '等待放号')
      await page.locator('#restart-dingtalk').click()
      await page.waitForFunction(() => document.querySelector('#login-entry-feedback').textContent.includes('已请求重启'))
      assert.equal(await error(page, 'phase'), '等待放号')
      await page.locator('#open-venue-login').click()
      await page.waitForFunction(() => document.querySelector('#login-entry-feedback').textContent.includes('已唤起钉钉'))
      assert.equal(await error(page, 'phase'), '等待放号')
      assert.equal(await page.locator('#target-date-value').isDisabled(), true)
      assert.equal(await page.locator('.court-card').first().isDisabled(), true)
      await page.locator('#stop').click()
      await phase(page, '任务已停止')
      await page.locator('#start').click()
      await phase(page, '恢复任务')
      await phase(page, '预约已确认')
      assert.match(await error(page, 'notice-message'), /6 号场.*14:00–16:00.*同行邀请/)
      await page.locator('#start').click()
      await phase(page, '预约结果待核对')
      assert.match(await error(page, 'notice-message'), /我的预约/)
      await page.locator('#refresh').click()
      await phase(page, '登录有效')
      await page.locator('#restart-dingtalk').click()
      await phase(page, '正在重启钉钉')
      await phase(page, '登录有效')
      await page.locator('#start').click()
      await phase(page, '等待钉钉登录')
      await page.locator('#retry-login').click()
      await phase(page, '任务已停止')
      assert.match(await error(page, 'login-status'), /预约接口登录有效.*最近验证成功/)
      assert.equal(await page.locator('#retry-login').isHidden(), true)
      async function setBeijingTime(iso) {
        const stamp = Date.parse(iso)
        await app.evaluate((_electron, stamp) => { Date.now = () => stamp }, stamp)
        await page.clock.setSystemTime(new Date(stamp))
        await page.evaluate(() => window.dispatchEvent(new Event('focus')))
      }
      await setBeijingTime('2026-12-31T23:59:50+08:00')
      await page.waitForFunction(() => document.querySelector('#hero-date').textContent === '2027-01-02')
      await page.waitForFunction(() => document.querySelector('#countdown').textContent === '本轮已结束')
      await setBeijingTime('2027-01-01T00:00:02+08:00')
      await page.waitForFunction(() => document.querySelector('#hero-date').textContent === '2027-01-03')
      await page.locator('#target-date-value').click()
      await page.locator('[data-date="2027-01-08"]').click()
      await page.waitForFunction(() => document.querySelector('#release').textContent.startsWith('2027-01-06'))
      await setBeijingTime('2027-01-02T10:00:00+08:00')
      assert.equal(await error(page, 'target-date-value'), '2027-01-08')
      await page.locator('#target-date-value').click()
      await page.getByRole('button', { name: '上个月', exact: true }).click()
      await page.getByRole('grid', { name: '2026 年 12 月' }).waitFor()
      await page.getByRole('button', { name: '后天', exact: true }).click()
      assert.equal(await error(page, 'target-date-value'), '2027-01-04')
      await setBeijingTime('2027-01-03T00:00:02+08:00')
      await page.waitForFunction(() => document.querySelector('#hero-date').textContent === '2027-01-05')

      await page.locator('#earliest-start-value').press('Enter')
      assert.equal(await page.locator('#date-time-picker').evaluate(el => el.classList.contains('picker-instant')), true)
      assert.equal(await page.getByLabel('小时', { exact: true }).locator('option[value="09"]').count(), 0)
      await page.getByRole('button', { name: '12:00', exact: true }).click()
      await page.locator('#earliest-start-value').click()
      await page.getByLabel('分钟', { exact: true }).selectOption('37')
      await page.keyboard.press('Escape')
      assert.equal(await error(page, 'earliest-start-value'), '12:00')
      assert.equal(await page.locator('#earliest-start-value').evaluate(el => el === document.activeElement), true)
      await page.locator('.advanced summary').click()
      await page.locator('#release-time-value').click()
      await page.getByRole('button', { name: '21:00', exact: true }).click()
      await page.waitForFunction(() => document.querySelector('#release').textContent === '2027-01-03 21:00:00')
      await page.locator('#release-override-value').click()
      await page.locator('[data-date="2027-01-04"]').click()
      await page.getByLabel('小时', { exact: true }).selectOption('19')
      await page.getByLabel('分钟', { exact: true }).selectOption('58')
      await page.getByLabel('秒', { exact: true }).selectOption('37')
      await page.getByRole('button', { name: '应用', exact: true }).click()
      await page.waitForFunction(() => document.querySelector('#release').textContent === '2027-01-04 19:58:37')
      await page.locator('#release-override-value').click()
      await page.getByRole('button', { name: '清除覆盖', exact: true }).click()
      await page.waitForFunction(() => document.querySelector('#release').textContent === '2027-01-03 21:00:00')

      const court = id => page.locator('#courts button[data-court="' + id + '"]')
      const currentOrder = () => page.locator('#courts li').allTextContents()
      const initial = await currentOrder()
      await court(6).focus()
      await page.keyboard.press('Space')
      await page.keyboard.press('ArrowDown')
      await page.keyboard.press('Escape')
      assert.deepEqual(await currentOrder(), initial)
      await page.keyboard.press('Space')
      await page.keyboard.press('ArrowRight')
      await page.keyboard.press('Space')
      assert.deepEqual((await currentOrder()).slice(0, 2), ['7', '6'])
      await page.locator('#participation-toggle').click()
      await page.locator('#participants label').filter({ hasText: /^7 号$/ }).locator('input').uncheck()
      assert.equal(await court(7).count(), 0)
      await page.locator('#participants label').filter({ hasText: /^7 号$/ }).locator('input').check()
      assert.equal((await currentOrder()).at(-1), '7')
      for (const check of await page.locator('#participants input').all()) {
        if (await check.isEnabled() && await check.isChecked()) await check.uncheck()
      }
      assert.equal(await page.locator('#participants input:disabled').count(), 1)
      const activeAfterDisable = await currentOrder()
      assert.equal(activeAfterDisable.length, 1)
      for (const check of await page.locator('#participants input').all()) {
        if (!await check.isChecked()) await check.check()
      }
      assert.equal((await currentOrder())[0], activeAfterDisable[0])
      await page.locator('#participation-toggle').click()

      // Restore the fixture order through the true renderer load path for cross-row gestures.
      await page.reload()
      await page.clock.setSystemTime(new Date('2027-01-03T00:00:02+08:00'))
      await page.locator('#start:enabled').waitFor()

      await page.locator('#courts').scrollIntoViewIfNeeded()
      const center = async id => {
        const b = await court(id).boundingBox()
        return [b.x + b.width / 2, b.y + b.height / 2]
      }
      const move = async (from, to, releaseInside = true) => {
        const startPoint = await center(from)
        const targetPoint = await center(to)
        await page.mouse.move(...startPoint)
        await page.mouse.down()
        await page.mouse.move(...targetPoint, { steps: 8 })
        if (!releaseInside) await page.mouse.move(4, 4)
        await page.mouse.up()
      }
      const beforeDrag = await currentOrder()
      await move(6, 7, false)
      assert.deepEqual(await currentOrder(), beforeDrag)
      await page.waitForFunction(() => !document.querySelector('.court-settling'))
      const reverseStart = await center(6)
      const reverseEnd = await center(7)
      await page.mouse.move(...reverseStart)
      await page.mouse.down()
      await page.mouse.move(...reverseEnd, { steps: 5 })
      await page.mouse.move(...reverseStart)
      await page.mouse.up()
      assert.deepEqual(await currentOrder(), beforeDrag)
      await page.waitForFunction(() => !document.querySelector('.court-settling'))
      await move(6, 7)
      assert.equal((await currentOrder())[1], '6')
      await page.emulateMedia({ reducedMotion: 'reduce' })
      await page.waitForFunction(() => !document.querySelector('.court-settling'))
      await move(6, 12)
      assert.equal((await currentOrder()).at(-1), '6')
      assert.equal(await court(6).evaluate(el => el.getAnimations().length), 0)
      const cdp = await page.context().newCDPSession(page)
      await cdp.send('Emulation.setTouchEmulationEnabled', { enabled: true })
      const [tx, ty] = await center(6)
      const [endX, endY] = await center(7)
      await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: tx, y: ty }] })
      await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: endX, y: endY }] })
      await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
      assert.equal((await currentOrder())[0], '6')
      await cdp.detach()
      await page.locator('#save').click()
      await phase(page, '配置已保存')
      const saved = (await page.evaluate(() => window.venue.load())).data.config
      assert.deepEqual(saved.court_priority.map(String), await currentOrder())
      assert.equal(saved.earliest_start, '10:00')
      assert.equal(saved.release_time, '20:00')
      console.log('Fixture UI: countdown, candidate order, stop, renew/restart, success, recovery, refresh passed')
      return
    }
    const count = await error(page, 'candidate-count')
    await app.close()
    const disposable = mkdtempSync(join(tmpdir(), 'hdu-config-test-'))
    const isolated = { env: { ...options.env, LOCALAPPDATA: disposable, HDU_DESKTOP_TEST_UI: join(disposable, 'ui') } }
    ;({ app, page } = await launch(isolated))
    await page.locator('#min_minutes').fill('75')
    await page.locator('#save').click()
    await phase(page, '配置已保存')
    await app.close()
    ;({ app, page } = await launch(isolated))
    assert.equal(await page.locator('#min_minutes').inputValue(), '75')
    console.log(JSON.stringify({ realReadOnly: count, packaging: 'x64', strippedPath: true, configPersisted: true }))
  } finally {
    await app.close()
  }
}

main().catch(error => {
  console.error(error)
  process.exitCode = 1
})
